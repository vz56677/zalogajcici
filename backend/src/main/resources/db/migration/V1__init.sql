CREATE TABLE korisnik (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ime text NOT NULL,
    email text NOT NULL,
    oauth_provider text NOT NULL,
    oauth_subject text NOT NULL,
    uloga text NOT NULL CHECK (uloga IN ('KUPAC', 'PRODAVAC', 'ORGANIZACIJA', 'ADMIN')),
    aktivan boolean NOT NULL DEFAULT true,
    kontakt text,
    podrucje_djelovanja text,
    status_odobrenja text,
    UNIQUE (oauth_provider, oauth_subject),
    CHECK (
        (uloga = 'ORGANIZACIJA' AND status_odobrenja IS NOT NULL
            AND status_odobrenja IN ('NA_CEKANJU', 'ODOBRENO', 'ODBIJENO'))
        OR (uloga <> 'ORGANIZACIJA' AND status_odobrenja IS NULL)
    )
);

CREATE TABLE prodajno_mjesto (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vlasnik_id bigint NOT NULL REFERENCES korisnik(id),
    naziv text NOT NULL,
    vrsta text NOT NULL,
    adresa text NOT NULL,
    kontakt text NOT NULL,
    logo_url text,
    sirina double precision NOT NULL CHECK (sirina BETWEEN -90 AND 90),
    duzina double precision NOT NULL CHECK (duzina BETWEEN -180 AND 180)
);

CREATE TABLE pristup_mjestu (
    prodajno_mjesto_id bigint REFERENCES prodajno_mjesto(id),
    korisnik_id bigint REFERENCES korisnik(id),
    PRIMARY KEY (prodajno_mjesto_id, korisnik_id)
);

CREATE TABLE radno_vrijeme (
    prodajno_mjesto_id bigint REFERENCES prodajno_mjesto(id),
    datum date,
    vrijeme_od time NOT NULL,
    vrijeme_do time NOT NULL,
    PRIMARY KEY (prodajno_mjesto_id, datum),
    CHECK (vrijeme_od <> vrijeme_do)
);

CREATE TABLE ponuda (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prodajno_mjesto_id bigint NOT NULL REFERENCES prodajno_mjesto(id),
    vrsta text NOT NULL CHECK (vrsta IN ('PROIZVOD', 'PAKET')),
    namjena text NOT NULL DEFAULT 'PRODAJA'
        CHECK (namjena IN ('PRODAJA', 'DONACIJA')),
    naziv text NOT NULL,
    kategorija text NOT NULL,
    opis text,
    fotografija_url text,
    redovna_cijena numeric(12,2) NOT NULL CHECK (redovna_cijena >= 0),
    prodajna_cijena numeric(12,2) NOT NULL CHECK (prodajna_cijena >= 0),
    raspolozivo numeric(10,2) NOT NULL CHECK (raspolozivo >= 0),
    jedinica_mjere text NOT NULL DEFAULT 'kom',
    objavljeno_u timestamptz NOT NULL DEFAULT now(),
    preuzimanje_od timestamptz NOT NULL,
    preuzimanje_do timestamptz NOT NULL,
    rok_upotrebe timestamptz,
    aktivna boolean NOT NULL DEFAULT true,
    UNIQUE (id, prodajno_mjesto_id),
    CHECK (preuzimanje_od < preuzimanje_do),
    CHECK (rok_upotrebe IS NULL OR preuzimanje_do <= rok_upotrebe),
    CHECK (namjena <> 'DONACIJA' OR prodajna_cijena = 0),
    CHECK (vrsta <> 'PAKET' OR
        (jedinica_mjere = 'kom' AND raspolozivo = trunc(raspolozivo)))
);

CREATE TABLE rezervacija (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kupac_id bigint NOT NULL REFERENCES korisnik(id),
    prodajno_mjesto_id bigint NOT NULL REFERENCES prodajno_mjesto(id),
    kod_preuzimanja text UNIQUE,
    status text NOT NULL CHECK (status IN (
        'CEKA_UPLATU', 'AKTIVNA', 'PREUZETA', 'OTKAZANA', 'ISTEKLA'
    )),
    kreirana_u timestamptz NOT NULL DEFAULT now(),
    rok_preuzimanja timestamptz NOT NULL,
    preuzeta_u timestamptz,
    preuzimanje_potvrdio_id bigint REFERENCES korisnik(id),
    UNIQUE (id, prodajno_mjesto_id),
    CHECK (status NOT IN ('AKTIVNA', 'PREUZETA') OR kod_preuzimanja IS NOT NULL),
    CHECK (
        (status = 'PREUZETA' AND preuzeta_u IS NOT NULL
            AND preuzimanje_potvrdio_id IS NOT NULL)
        OR (status <> 'PREUZETA' AND preuzeta_u IS NULL
            AND preuzimanje_potvrdio_id IS NULL)
    )
);

CREATE TABLE stavka_rezervacije (
    rezervacija_id bigint,
    ponuda_id bigint,
    prodajno_mjesto_id bigint NOT NULL,
    kolicina numeric(10,2) NOT NULL CHECK (kolicina > 0),
    jedinicna_cijena numeric(12,2) NOT NULL CHECK (jedinicna_cijena >= 0),
    PRIMARY KEY (rezervacija_id, ponuda_id),
    FOREIGN KEY (rezervacija_id, prodajno_mjesto_id)
        REFERENCES rezervacija(id, prodajno_mjesto_id),
    FOREIGN KEY (ponuda_id, prodajno_mjesto_id)
        REFERENCES ponuda(id, prodajno_mjesto_id)
);

CREATE TABLE zahtjev_donacije (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacija_id bigint NOT NULL REFERENCES korisnik(id),
    ponuda_id bigint NOT NULL REFERENCES ponuda(id),
    trazena_kolicina numeric(10,2) NOT NULL CHECK (trazena_kolicina > 0),
    status text NOT NULL DEFAULT 'NA_CEKANJU'
        CHECK (status IN ('NA_CEKANJU', 'ODOBRENO', 'ODBIJENO')),
    poslan_u timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE akcija (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizator_id bigint NOT NULL REFERENCES korisnik(id),
    naziv text NOT NULL,
    opis text NOT NULL,
    lokacija text NOT NULL,
    sirina double precision CHECK (sirina BETWEEN -90 AND 90),
    duzina double precision CHECK (duzina BETWEEN -180 AND 180),
    pocetak timestamptz NOT NULL,
    zavrsetak timestamptz NOT NULL,
    CHECK (pocetak < zavrsetak)
);

CREATE TABLE potreba_akcije (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    akcija_id bigint NOT NULL REFERENCES akcija(id),
    naziv_proizvoda text NOT NULL,
    jedinica_mjere text NOT NULL,
    trazena_kolicina numeric(10,2) NOT NULL CHECK (trazena_kolicina > 0),
    UNIQUE (akcija_id, naziv_proizvoda)
);

CREATE TABLE donacija_akcije (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    potreba_id bigint NOT NULL REFERENCES potreba_akcije(id),
    donator_id bigint NOT NULL REFERENCES korisnik(id),
    najavljena_kolicina numeric(10,2) NOT NULL CHECK (najavljena_kolicina > 0),
    primljena_kolicina numeric(10,2) CHECK (primljena_kolicina > 0),
    primljena_u timestamptz,
    CHECK ((primljena_kolicina IS NULL) = (primljena_u IS NULL))
);

CREATE TABLE cjenik_clanarine (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vrsta text NOT NULL CHECK (vrsta IN ('MJESECNA', 'GODISNJA')),
    vrijedi_od timestamptz NOT NULL DEFAULT now(),
    cijena numeric(12,2) NOT NULL CHECK (cijena >= 0),
    UNIQUE (vrsta, vrijedi_od)
);

CREATE TABLE clanarina (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prodavac_id bigint NOT NULL REFERENCES korisnik(id),
    cjenik_id bigint NOT NULL REFERENCES cjenik_clanarine(id),
    vrijedi_od timestamptz NOT NULL,
    vrijedi_do timestamptz NOT NULL,
    iznos numeric(12,2) NOT NULL CHECK (iznos >= 0),
    CHECK (vrijedi_od < vrijedi_do)
);

CREATE TABLE uplata (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rezervacija_id bigint REFERENCES rezervacija(id),
    clanarina_id bigint REFERENCES clanarina(id),
    izvorna_uplata_id bigint REFERENCES uplata(id),
    vrsta text NOT NULL CHECK (vrsta IN ('UPLATA', 'POVRAT')),
    nacin text NOT NULL CHECK (nacin IN ('PAYPAL', 'KARTICA')),
    status text NOT NULL CHECK (status IN ('NA_CEKANJU', 'USPJESNO', 'NEUSPJESNO')),
    iznos numeric(12,2) NOT NULL CHECK (iznos > 0),
    pruzatelj text,
    vanjski_id text,
    evidentirana_u timestamptz NOT NULL DEFAULT now(),
    UNIQUE (pruzatelj, vanjski_id),
    CHECK ((rezervacija_id IS NULL) <> (clanarina_id IS NULL)),
    CHECK (vanjski_id IS NULL OR pruzatelj IS NOT NULL),
    CHECK (
        (vrsta = 'UPLATA' AND izvorna_uplata_id IS NULL)
        OR (vrsta = 'POVRAT' AND izvorna_uplata_id IS NOT NULL)
    ),
    CHECK (izvorna_uplata_id IS NULL OR izvorna_uplata_id <> id)
);

CREATE TABLE recenzija (
    rezervacija_id bigint PRIMARY KEY REFERENCES rezervacija(id),
    ocjena smallint NOT NULL CHECK (ocjena BETWEEN 1 AND 5),
    komentar text,
    objavljena_u timestamptz NOT NULL DEFAULT now(),
    odgovor text,
    odgovoreno_u timestamptz,
    CHECK ((odgovor IS NULL) = (odgovoreno_u IS NULL))
);

CREATE TABLE pretplata_obavijesti (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    korisnik_id bigint NOT NULL REFERENCES korisnik(id),
    prodajno_mjesto_id bigint REFERENCES prodajno_mjesto(id),
    kategorija text,
    CHECK ((prodajno_mjesto_id IS NULL) <> (kategorija IS NULL)),
    UNIQUE (korisnik_id, prodajno_mjesto_id),
    UNIQUE (korisnik_id, kategorija)
);
